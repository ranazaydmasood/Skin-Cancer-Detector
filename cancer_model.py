plt.ylabel("Number of Images")
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

# 4. Display sample images from all 7 classes
plt.figure(figsize=(14, 6))
for target_class in range(7):
    # Find index of the first image belonging to target_class
    idx = np.where(y_train == target_class)[0][0]

    plt.subplot(1, 7, target_class + 1)
    plt.imshow(x_train[idx])
    plt.title(f"Class {target_class}")
    plt.axis('off')
plt.tight_layout()
plt.show()

"""### Data Preprocessing
We will normalize the images, prepare the train, validation, and test splits, and verify the shapes of the datasets before training.
"""

# 1. Normalize all images by dividing pixel values by 255.0
x_train_preprocessed = x_train.astype('float32') / 255.0
x_val_preprocessed = x_val.astype('float32') / 255.0
x_test_preprocessed = x_test.astype('float32') / 255.0

# 2. Labels are already in integer format (0-6), which is perfect for SparseCategoricalCrossentropy
y_train_preprocessed = y_train
y_val_preprocessed = y_val
y_test_preprocessed = y_test

# 3. Check all dataset shapes and image dimensions (should remain 28x28x3)
print("Preprocessed Dataset Shapes:")
print(f"Train images: {x_train_preprocessed.shape}, Train labels: {y_train_preprocessed.shape}")
print(f"Validation images: {x_val_preprocessed.shape}, Validation labels: {y_val_preprocessed.shape}")
print(f"Test images: {x_test_preprocessed.shape}, Test labels: {y_test_preprocessed.shape}")

# Confirming image shape explicitly
print(f"\nSingle image shape: {x_train_preprocessed[0].shape}")
print(f"Pixel value range: [{x_train_preprocessed.min()}, {x_train_preprocessed.max()}]")

"""### Lightweight CNN Model Architecture
We will define the model using the exact layers, filters, and neurons requested to guarantee an ultra-lightweight footprint.
"""

import tensorflow as tf
from tensorflow.keras import layers, models

# Define the lightweight CNN model based on strict requirements
model = models.Sequential([
    # 1. Input layer with shape (28, 28, 3)
    layers.Input(shape=(28, 28, 3)),

    # 2. First Conv2D layer with 8 filters and MaxPooling2D
    layers.Conv2D(8, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),

    # 3. Second Conv2D layer with 16 filters and MaxPooling2D
    layers.Conv2D(16, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),

    # 4. Flatten layer
    layers.Flatten(),

    # 5. Dense layer with 32 neurons and Dropout (0.3)
    layers.Dense(32, activation='relu'),
    layers.Dropout(0.3),

    # 6. Output Dense layer with 7 neurons and softmax activation
    layers.Dense(7, activation='softmax')
])

# Compile the model
model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Display summary
model.summary()

# Estimate model footprint
total_params = model.count_params()
estimated_size_kb = (total_params * 4) / 1024  # Assuming float32 (4 bytes per parameter)
print(f"\nTotal Parameters: {total_params:,}")
print(f"Estimated Parameter Size: {estimated_size_kb:.2f} KB")

"""### Model Training
We will train our compiled lightweight CNN model for 10 epochs using the preprocessed training dataset and validate it with the validation set.
"""

import os

# Train the model
history = model.fit(
    x_train_preprocessed,
    y_train_preprocessed,
    epochs=10,
    batch_size=32,
    validation_data=(x_val_preprocessed, y_val_preprocessed)
)

# Save the trained model in Keras format
model_save_path = 'skin_cancer_model.keras'
model.save(model_save_path)

# Verify saved model size
file_size_mb = os.path.getsize(model_save_path) / (1024 * 1024)
print(f"\nSaved model file size: {file_size_mb:.4f} MB")
assert file_size_mb < 25.0, "Saved model exceeds 25 MB!"

"""### Model Evaluation
We will evaluate the trained lightweight model on the test split, visualize the training performance history, and generate a classification report and confusion matrix to analyze the model's predictions across all 7 classes.
"""

import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.metrics import classification_report, confusion_matrix

# 1. Evaluate the model using the test dataset
test_loss, test_acc = model.evaluate(x_test_preprocessed, y_test_preprocessed, verbose=0)
print(f"Test Loss: {test_loss:.4f}")
print(f"Test Accuracy: {test_acc:.4f}\n")

# 2. Plot Training and Validation Accuracy / Loss Graphs
epochs_range = range(1, len(history.history['accuracy']) + 1)

plt.figure(figsize=(14, 5))

# Accuracy Graph
plt.subplot(1, 2, 1)
plt.plot(epochs_range, history.history['accuracy'], label='Training Accuracy', marker='o')
plt.plot(epochs_range, history.history['val_accuracy'], label='Validation Accuracy', marker='o')
plt.title('Training and Validation Accuracy')
plt.xlabel('Epochs')
plt.ylabel('Accuracy')
plt.legend(loc='lower right')
plt.grid(True, linestyle='--', alpha=0.5)

# Loss Graph
plt.subplot(1, 2, 2)
plt.plot(epochs_range, history.history['loss'], label='Training Loss', marker='o')
plt.plot(epochs_range, history.history['val_loss'], label='Validation Loss', marker='o')
plt.title('Training and Validation Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss')
plt.legend(loc='upper right')
plt.grid(True, linestyle='--', alpha=0.5)

plt.tight_layout()
plt.show()

# 3. Generate predictions and class metrics
y_pred_probs = model.predict(x_test_preprocessed)
y_pred = np.argmax(y_pred_probs, axis=1)
y_true = y_test_preprocessed.flatten()

# 4. Display Classification Report
print("Classification Report:")
print(classification_report(y_true, y_pred, target_names=[f"Class {i}" for i in range(7)]))

# 5. Generate and plot Confusion Matrix
cm = confusion_matrix(y_true, y_pred)

plt.figure(figsize=(8, 6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=[f"Class {i}" for i in range(7)],
            yticklabels=[f"Class {i}" for i in range(7)])
plt.title('Confusion Matrix on Test Dataset')
plt.ylabel('True Class')
plt.xlabel('Predicted Class')
plt.show()

"""### Build, Train, and Save the Lightweight CNN Model
We will define a simple, lightweight CNN architecture from scratch to ensure the saved model (`skin_cancer_model.keras`) is well under the 25 MB limit.
"""

import os
from tensorflow.keras import layers, models

# Normalize image pixel values to [0, 1]
x_train_norm = x_train.astype('float32') / 255.0
x_val_norm = x_val.astype('float32') / 255.0
x_test_norm = x_test.astype('float32') / 255.0

# Build a lightweight CNN model from scratch
model = models.Sequential([
    layers.Input(shape=(28, 28, 3)),
    layers.Conv2D(32, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation='relu', padding='same'),
    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dropout(0.5),
    layers.Dense(7, activation='softmax')
])

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

model.summary()

# Train the model
history = model.fit(
    x_train_norm, y_train,
    epochs=15,
    batch_size=32,
    validation_data=(x_val_norm, y_val)
)

# Save the model in Keras format
model_save_path = 'skin_cancer_model.keras'
model.save(model_save_path)

# Check the file size of the saved model
file_size_mb = os.path.getsize(model_save_path) / (1024 * 1024)
print(f"\nSaved model size: {file_size_mb:.2f} MB")
assert file_size_mb < 25.0, "The saved model size exceeds the 25 MB limit!"

# Evaluate the model on test data
test_loss, test_acc = model.evaluate(x_test_norm, y_test, verbose=0)
print(f"Test loss: {test_loss:.4f}")
print(f"Test accuracy: {test_acc:.4f}")

