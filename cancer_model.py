import numpy as np
import tensorflow as tf

# Load the dataset
data_path = '/content/dermamnist (1).npz'
data = np.load(data_path)

# Extract splits
x_train = data['train_images']
y_train = data['train_labels']
x_val = data['val_images']
y_val = data['val_labels']
x_test = data['test_images']
y_test = data['test_labels']

# Display information
print(f"Train images shape: {x_train.shape}, labels shape: {y_train.shape}")
print(f"Validation images shape: {x_val.shape}, labels shape: {y_val.shape}")
print(f"Test images shape: {x_test.shape}, labels shape: {y_test.shape}")
print(f"Unique labels: {np.unique(y_train)}")

"""### Exploratory Data Analysis (EDA)
We will analyze the class balance, image dimensions, verify for missing values, and visualize sample images from each of the 7 classes.
"""

import numpy as np
import matplotlib.pyplot as plt

# 1. Total and Split Image Counts
total_images = len(x_train) + len(x_val) + len(x_test)
print(f"Total number of images: {total_images}")
print(f"Training images: {len(x_train)}")
print(f"Validation images: {len(x_val)}")
print(f"Testing images: {len(x_test)}\n")

# 2. Check Image Dimensions and Missing Values
print(f"Image dimensions: {x_train.shape[1:3]} with {x_train.shape[3]} channels.")
print(f"Any missing values in train images? {np.isnan(x_train).any()}")
print(f"Any missing values in train labels? {np.isnan(y_train).any()}")

# 3. Class Counts & Bar Chart Distribution
classes, counts = np.unique(y_train, return_counts=True)
class_names = [f"Class {c}" for c in classes]

for name, count in zip(class_names, counts):
    print(f"{name}: {count} images ({count/len(y_train)*100:.2f}%)")

# Plotting distribution
plt.figure(figsize=(8, 4))
plt.bar(class_names, counts, color='skyblue', edgecolor='black')
plt.title("Class Distribution in Training Set")
